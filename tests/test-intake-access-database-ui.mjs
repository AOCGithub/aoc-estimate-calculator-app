// Real Supabase + browser test. --live explicitly targets the AOC domain and makes one AI call.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { chromium } from 'playwright-core';
import postgres from 'postgres';

const require = createRequire(import.meta.url);
const fixture = require('./fixtures/commercial.cjs');
const engine = require('../public/journey-calculation.js');
const live = process.argv.includes('--live');
const liveAi = live && !process.argv.includes('--skip-ai');
const baseURL = live ? 'https://estimate.alwaysopencommerce.com' : 'http://localhost:5173';
const connection = process.env.POSTGRES_URL || process.env.POSTGRES_URL_NON_POOLING;
assert.ok(connection, 'Run through Vercel env run for database credentials.');
const sql = postgres(connection, { prepare: false, max: 1, connect_timeout: 15, ssl: 'require' });
const company = (live ? 'Production Smoke ' : 'Intake Only ') + randomUUID();
const name = 'Synthetic Intake Only Test';
const executablePath = [process.env.CHROME_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', '/usr/bin/google-chrome', '/usr/bin/chromium'].find(path => path && existsSync(path));
let browser;
let stage = 'startup';
let debugPage;
try {
  console.log('Target: ' + baseURL + (liveAi ? ' (one paid synthetic AI request)' : ' (no paid AI)'));
  const status = await (await fetch(baseURL + '/api/access/status', { signal: AbortSignal.timeout(8000) })).json();
  assert.equal(status.intakeOnly, true, 'Start npm run dev:access for temporary save-and-continue access.');
  assert.equal(status.recordsEnabled, true, 'Local calculation recording must be enabled.');
  assert.equal(Boolean(status.manualApproval), false);
  browser = await chromium.launch({ executablePath, headless: true });
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    const page = await context.newPage();
    debugPage = page;
    page.setDefaultTimeout(15000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(baseURL, { waitUntil: 'networkidle' });
    await page.getByRole('button', { name: 'Continue to calculator' }).waitFor();
    assert.equal(await page.locator('input:not([type="checkbox"])').count(), 5);
    const consent = page.getByRole('checkbox', { name: /Save my details and estimates/ });
    assert.equal(await consent.isChecked(), false);
    assert.equal(await page.getByText(/Verification and approval are on hold/).count(), 1);
    assert.equal(await page.getByText(/without saving your business details or estimate records/).count(), 1);
    await page.getByRole('button', { name: 'Continue to calculator' }).click();
    assert.equal(await page.locator('.area').count(), 0, 'Required fields must still be completed.');
    const email = 'intake-' + width + '-' + randomUUID().slice(0, 8) + '@example.com';
    const profile = { name, company, website: 'example.com', role: 'Synthetic tester', businessEmail: email };
    const invalid = await context.request.post(baseURL + '/api/access/verify', { headers: { origin: baseURL }, data: { ...profile, role: '' } });
    assert.equal(invalid.status(), 400);
    let rows = await sql`select id from public.access_requests where company = ${company} and business_email = ${email}`;
    assert.equal(rows.length, 0);
    for (const [field, value] of Object.entries(profile)) await page.locator('#access-' + field).fill(value);
    await consent.check();
    await page.route('**/api/access/verify', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Synthetic save failure. Please try again.' }) }));
    await page.getByRole('button', { name: 'Continue to calculator' }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByLabel('Business email').inputValue(), email);
    assert.equal(await page.locator('.area').count(), 0);
    await page.unroute('**/api/access/verify');
    await page.getByRole('button', { name: 'Continue to calculator' }).click();
    await page.locator('.area').first().waitFor();
    assert.equal(await page.locator('.area').count(), 12, 'Any valid saved submission can enter without approval.');
    assert.equal(await page.getByText('Access is limited to AOC-approved participants.', { exact: false }).count(), 0);
    rows = await sql`select name, company, website, role, business_email, review_status from public.access_requests where company = ${company} and business_email = ${email}`;
    assert.deepEqual(rows.map(row => ({ ...row })), [{ name, company, website: 'https://example.com/', role: profile.role, business_email: email, review_status: 'pending' }]);
    const cookies = await context.cookies();
    assert.equal(cookies.find(cookie => cookie.name === 'aoc_estimator_access').httpOnly, true);
    if (live) assert.equal(cookies.find(cookie => cookie.name === 'aoc_estimator_access').secure, true);
    assert.equal(cookies.some(cookie => cookie.name === 'aoc_estimator_review_access'), false);
    if (liveAi && width === 1440) {
      stage = 'live paid-advertising AI prefill';
      await page.getByRole('button', { name: 'Paid advertising', exact: true }).click();
      await page.getByRole('button', { name: /^Describe the work/ }).click();
      const description = 'We need a workflow automation to prepare weekly paid advertising reports and draft ad copy for one Shopify store. We use Meta Ads Manager and Google Sheets and advertise in English on Facebook and Instagram. Staff review and publish everything manually. The automation must only prepare drafts: never publish ads, change budgets or change campaigns. We do not know how many people will use it, who will manage the finished workflow, or how much time it will save.';
      await page.locator('#description').fill(description);
      const organized = page.waitForResponse(response => response.url() === baseURL + '/api/journey/analyze', { timeout: 65000 });
      await page.getByRole('button', { name: /Organize my description/ }).click();
      const aiResponse = await organized;
      assert.equal(aiResponse.status(), 200, 'Live AI must return a successful structured response.');
      const ai = await aiResponse.json();
      assert.ok(ai.analysis && !ai.localFallback, 'This check must use the live provider, not local fallback.');
      assert.ok(ai.analysis.facts.length > 0);
      for (const fact of ai.analysis.facts) assert.ok(description.includes(fact.quote));
      await page.waitForFunction(() => globalThis.AOCJourney.getState().step === 3 && !globalThis.AOCJourney.getState().working);
      const prefilled = await page.evaluate(() => globalThis.AOCJourney.getState());
      for (const key of ['people_count', 'team_time', 'responsibility_split']) assert.ok(prefilled.answers[key] == null || prefilled.answers[key] === '', key + ' must stay unknown.');
      assert.notEqual(prefilled.answers.action_mode, 'automatic');
      console.log('PASS: One live paid-advertising AI request populated supported facts and left unknowns blank.');
      await page.locator('#restart').click();
      await page.getByRole('dialog').getByRole('button', { name: 'Start over', exact: true }).click();
      await page.locator('.area').first().waitFor();
    }
    const payload = { area: fixture.area, confirmed: true, answers: Object.fromEntries(Object.entries(fixture).filter(([key]) => !['area', 'process_confirmed'].includes(key))) };
    const result = await context.request.post(baseURL + '/api/journey/calculate', { headers: { origin: baseURL }, data: payload });
    assert.equal(result.status(), 200);
    assert.deepEqual(await result.json(), { ...engine.calculate(payload), source: 'server', record: { saved: true } });
    const [owner] = await sql`select id from public.access_requests where company = ${company} and business_email = ${email}`;
    let records = await sql`select * from public.estimates where access_request_id = ${owner.id} order by created_at`;
    assert.equal(records.length, 1);
    assert.deepEqual(records[0].answers, payload.answers);
    assert.deepEqual(records[0].result, engine.calculate(payload).result);
    assert.equal(records[0].business_area, payload.area);
    assert.equal(records[0].pricing_version, '2026-10-21-commercial-v1');
    const changed = { ...payload, answers: { ...payload.answers, team_time: 90 } };
    const changedResponse = await context.request.post(baseURL + '/api/journey/calculate', { headers: { origin: baseURL }, data: changed });
    assert.equal((await changedResponse.json()).record.saved, true);
    const cleared = { ...payload, answers: { ...payload.answers, team_time: '' } };
    const clearedResponse = await context.request.post(baseURL + '/api/journey/calculate', { headers: { origin: baseURL }, data: cleared });
    assert.equal((await clearedResponse.json()).record.saved, true);
    records = await sql`select answers, result from public.estimates where access_request_id = ${owner.id} order by created_at`;
    assert.equal(records.length, 3);
    assert.equal(records[0].answers.team_time, 40, 'Older snapshots must not be overwritten.');
    assert.equal(records[1].answers.team_time, 90);
    assert.equal(records[2].answers.team_time, '');
    assert.deepEqual(records[2].result, engine.calculate(cleared).result);
    // Drive the real Calculate button too; no paid organizer call is needed.
    stage = `${width}px choose area`;
    await page.locator('.area').first().click();
    await page.getByRole('button', { name: /^Describe the work/ }).click();
    await page.getByRole('button', { name: /Continue with editable fields/ }).click();
    await page.locator('#f_solution').selectOption('workflow');
    stage = `${width}px scope`;
    await page.getByText(/Process complexity/).click();
    await page.locator('#f_steps_band').selectOption('2');
    await page.locator('#f_variation_band').selectOption('1');
    await page.getByText(/Team and rollout/).click();
    await page.locator('#f_people_count').fill('3');
    await page.locator('#f_department_count').fill('2');
    await page.locator('#f_cadence').selectOption('monthly');
    await page.locator('#f_handover').selectOption('group');
    await page.getByRole('button', { name: /Continue/ }).click();
    stage = `${width}px apps`;
    await page.locator('#f_systems').fill('Wave');
    await page.locator('#f_legacy_system_check').selectOption('Standard');
    await page.getByRole('button', { name: /Continue/ }).click();
    stage = `${width}px data`;
    await page.locator('#f_documentation_readiness').selectOption('Notes or examples');
    await page.locator('#f_data_preparation_level').selectOption('Some preparation');
    await page.getByRole('button', { name: /Continue/ }).click();
    await page.getByRole('button', { name: /Continue/ }).click();
    stage = `${width}px service`;
    await page.locator('#f_responsibility_split').selectOption('aoc');
    await page.locator('#f_implementation_route').selectOption('project');
    await page.locator('#f_existing_client').selectOption('no');
    await page.locator('#f_action_mode').selectOption('draft');
    await page.getByRole('button', { name: /^Standard/ }).click();
    await page.locator('.check input').check();
    stage = `${width}px UI calculate`;
    await page.getByRole('button', { name: /Confirm details & calculate/ }).click();
    await page.getByText('Estimate calculated and saved.', { exact: true }).waitFor();
    assert.equal(await page.getByText('Access is limited to AOC-approved participants.', { exact: false }).count(), 0);
    const state = await page.evaluate(() => globalThis.AOCJourney.getState());
    records = await sql`select result from public.estimates where access_request_id = ${owner.id} order by created_at desc`;
    assert.equal(records.length, 4);
    assert.deepEqual(records[0].result, state.result);
    await page.route('**/api/journey/calculate', route => route.fulfill({ status: 200, contentType: 'application/json',
      body: JSON.stringify({ result: state.result, source: 'server', record: { saved: false,
        error: 'Your estimate was calculated, but could not be saved. Please calculate again to retry.' } }) }));
    await page.getByRole('button', { name: /Confirm details & calculate/ }).click();
    await page.getByText('Your estimate was calculated, but could not be saved. Please calculate again to retry.', { exact: true }).waitFor();
    assert.deepEqual(await page.evaluate(() => globalThis.AOCJourney.getState().result), state.result);
    await page.unroute('**/api/journey/calculate');
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('.area').first().waitFor();
    assert.equal(await page.locator('input[name="businessEmail"]').count(), 0, 'Active sessions do not repeat the entry form.');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(await page.evaluate(() => [Object.keys(localStorage), Object.keys(sessionStorage)]), [[], []]);
    await page.getByRole('button', { name: 'End session' }).click();
    await page.getByRole('button', { name: 'Continue to calculator' }).waitFor();
    assert.equal(await page.getByLabel('Your name').inputValue(), '');
    if (width === 390) await page.screenshot({ path: 'artifacts/intake-only-mobile.png', fullPage: true });
    const blocked = await context.request.post(baseURL + '/api/journey/calculate', { headers: { origin: baseURL }, data: payload });
    assert.equal(blocked.status(), 401);
    const privateEmail = 'private-' + randomUUID() + '@example.com';
    for (const [field, value] of Object.entries({ ...profile, businessEmail: privateEmail })) await page.locator('#access-' + field).fill(value);
    assert.equal(await consent.isChecked(), false, 'Saving must default off again after logout.');
    await page.getByRole('button', { name: 'Continue to calculator' }).click();
    await page.getByRole('note').filter({ hasText: 'Data saving is off.' }).waitFor();
    const privateState = await page.evaluate(() => globalThis.AOCJourney.getState());
    assert.equal(privateState.description, '');
    assert.deepEqual(privateState.answers, {}, 'Ending the previous session must clear private answers held on the page.');
    assert.equal(privateState.result, null);
    const privateRows = await sql`select id from public.access_requests where company = ${company} and business_email = ${privateEmail}`;
    assert.equal(privateRows.length, 0, 'No-save entry must not create a form record.');
    const privateCalculation = await context.request.post(baseURL + '/api/journey/calculate', { headers: { origin: baseURL }, data: payload });
    assert.equal(privateCalculation.status(), 200);
    const privateResult = await privateCalculation.json();
    assert.deepEqual(privateResult.result, engine.calculate(payload).result);
    assert.deepEqual(privateResult.record, { saved: false, skipped: true });
    const privateCookies = await context.cookies();
    const privateToken = JSON.parse(Buffer.from(privateCookies.find(cookie => cookie.name === 'aoc_estimator_access').value.split('.')[0], 'base64url').toString());
    assert.equal(privateToken.requestId, undefined);
    assert.equal(privateToken.saveData, false);
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('note').filter({ hasText: 'Data saving is off.' }).waitFor();
    assert.deepEqual(errors, []);
    await context.close();
    console.log(`PASS: Real Supabase + ${width}px optional saving, no-save entry/calculation, linked snapshots when selected, edited/cleared answers, Calculate button, pricing version, reload and logout.`);
  }
} catch (error) {
  console.error('Intake-only integration failed at', stage, ':', error instanceof assert.AssertionError || error.name === 'TimeoutError'
    ? error.message : (error.code || error.name));
  if (debugPage && !debugPage.isClosed()) await debugPage.screenshot({ path: 'artifacts/estimate-record-error.png', fullPage: true });
  process.exitCode = 1;
} finally {
  if (browser) await browser.close();
  const estimates = await sql`delete from public.estimates where access_request_id in
    (select id from public.access_requests where company = ${company} and name = ${name}) returning id`;
  console.log(`Removed ${estimates.length} synthetic estimate snapshots only.`);
  const removed = await sql`delete from public.access_requests where company = ${company} and name = ${name} returning id`;
  console.log(`Removed ${removed.length} synthetic intake test rows only. Existing submissions and approval data preserved.`);
  await sql.end({ timeout: 5 });
}
